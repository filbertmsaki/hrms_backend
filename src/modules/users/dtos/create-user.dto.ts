import {
  IsArray,
  IsEmail,
  IsNotEmpty,
  IsOptional,
  IsString,
  Matches,
  MinLength,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform, TransformFnParams } from 'class-transformer';
import { Role } from 'src/modules/roles/entities/role.entity';
import {
  TANZANIA_OR_UGANDA_PHONE_CANONICAL_REGEX,
  normalizeTanzaniaOrUgandaPhone,
} from '../../../common/utils/tanzania-phone.util';

export class CreateUserDto {
  @ApiProperty({
    description: 'Given name of the user.',
    example: 'John',
  })
  @IsString()
  @IsNotEmpty()
  first_name: string;

  @ApiProperty({
    description: 'Family name of the user.',
    example: 'Doe',
  })
  @IsString()
  @IsNotEmpty()
  last_name: string;

  @ApiProperty({
    description:
      'Tanzanian (+255) or Ugandan (+256) phone number in E.164 format.',
    example: '+255712345678',
  })
  @IsNotEmpty()
  @Transform(({ value }: TransformFnParams): unknown => {
    if (typeof value !== 'string') return value as unknown;
    return normalizeTanzaniaOrUgandaPhone(value) ?? value.trim();
  })
  @Matches(TANZANIA_OR_UGANDA_PHONE_CANONICAL_REGEX, {
    message:
      'Phone number must be a valid Tanzanian (+255) or Ugandan (+256) number, for example +255762650393 or +256772123456',
  })
  phone: string;

  @ApiProperty({
    description: 'Unique login email for the user.',
    example: 'john.doe@acme.co.tz',
  })
  @IsEmail()
  @IsNotEmpty()
  email: string;

  @ApiProperty({
    description: 'Initial password for the user account.',
    example: 'P@ssw0rd#2026',
    minLength: 6,
  })
  @IsString()
  @MinLength(6)
  @IsNotEmpty()
  password: string;

  @ApiPropertyOptional({
    description: 'Optional internal user number generated by the company.',
    example: 'EMP-2026-0015',
  })
  @IsString()
  @IsOptional()
  user_no?: string;

  @ApiPropertyOptional({
    description: 'Lifecycle status of the user account.',
    example: 'active',
  })
  @IsString()
  @IsOptional()
  status?: string;

  @ApiPropertyOptional({
    description: 'Roles assigned during user creation.',
    type: [Role],
  })
  @IsArray()
  @IsOptional()
  roles?: Role[];
}
